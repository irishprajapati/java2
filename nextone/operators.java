package nextone;

public class operators {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        System.out.println(a + b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        int x= 10;
        int y = 10;
        System.out.println(x == y);
        System.out.println(x!=y);
        System.out.println(x>y);
        System.out.println(x<y);
        System.out.println(x>=y);
        System.out.println(x<=y);
    }
}
